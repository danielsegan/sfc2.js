#!/usr/bin/env node
/**
 * Offline quarter-wave sine LUT and CORDIC arctangent table.
 * The sim imports the integers this writes. It does not call Math.sin.
 *
 *   node tools/generate-angle-lut.mjs          # write engine/core/angle-lut.ts
 *   node tools/generate-angle-lut.mjs --check  # fail if the committed file differs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const STEPS = 4096;
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outPath = join(root, 'engine', 'core', 'angle-lut.ts');

function quarterSine() {
  const values = [];
  for (let i = 0; i <= STEPS; i++) {
    const s = Math.sin((i / STEPS) * (Math.PI / 2));
    values.push(Math.round(s * 65536));
  }
  return values;
}

function cordicAtan() {
  const values = [];
  for (let i = 0; i < 16; i++) {
    values.push(Math.round((Math.atan(2 ** -i) / (2 * Math.PI)) * 65536));
  }
  return values;
}

function emit(sine, atan) {
  const lines = [];
  lines.push('/** Generated by tools/generate-angle-lut.mjs. Do not edit by hand. */');
  lines.push(`export const SIN_QUARTER_STEPS = ${STEPS};`);
  lines.push('');
  lines.push('/** Q16.16 sine of i/4096 of a right angle, including both endpoints. */');
  lines.push('export const SIN_QUARTER_LUT: readonly number[] = [');
  for (let i = 0; i < sine.length; i += 12) {
    lines.push(`  ${sine.slice(i, i + 12).join(', ')},`);
  }
  lines.push('];');
  lines.push('');
  lines.push('/** atan(2^-i) in BAM (65536 per turn), rounded to nearest. */');
  lines.push(`export const ATAN_CORDIC_BAM: readonly number[] = [${atan.join(', ')}];`);
  lines.push('');
  return `${lines.join('\n')}`;
}

const text = emit(quarterSine(), cordicAtan());
const check = process.argv.includes('--check');
if (check) {
  const current = readFileSync(outPath, 'utf8');
  if (current !== text) {
    console.error('angle LUT is stale. Run: node tools/generate-angle-lut.mjs');
    process.exit(1);
  }
  console.log('angle LUT matches the generator');
} else {
  writeFileSync(outPath, text);
  console.log(`wrote ${outPath}`);
}
